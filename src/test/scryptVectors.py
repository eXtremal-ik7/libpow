#!/usr/bin/env python3
# Generates scryptVectors.h for scrypt(N=1024, r=1, p=1) over an 80 byte block
# header used both as password and salt, the way Litecoin hashes. The digests
# come from the textbook scrypt below (RFC 7914 over hashlib.pbkdf2_hmac); it is
# checked against hashlib.scrypt when OpenSSL provides that.
#   python3 scryptVectors.py > scryptVectors.h
import hashlib

MASK32 = 0xFFFFFFFF

def rol(x, n):
    return ((x << n) | (x >> (32 - n))) & MASK32

def salsa20_8(b):
    x = list(b)
    def quarter(a, b, c, d):
        x[b] ^= rol((x[a] + x[d]) & MASK32, 7)
        x[c] ^= rol((x[b] + x[a]) & MASK32, 9)
        x[d] ^= rol((x[c] + x[b]) & MASK32, 13)
        x[a] ^= rol((x[d] + x[c]) & MASK32, 18)
    for _ in range(4):
        quarter(0, 4, 8, 12); quarter(5, 9, 13, 1); quarter(10, 14, 2, 6); quarter(15, 3, 7, 11)
        quarter(0, 1, 2, 3); quarter(5, 6, 7, 4); quarter(10, 11, 8, 9); quarter(15, 12, 13, 14)
    return [(x[i] + b[i]) & MASK32 for i in range(16)]

def block_mix(b):
    # r = 1: two 64 byte halves
    y0 = salsa20_8([b[i] ^ b[16 + i] for i in range(16)])
    y1 = salsa20_8([b[16 + i] ^ y0[i] for i in range(16)])
    return y0 + y1

def scrypt(header, n=1024):
    b = hashlib.pbkdf2_hmac('sha256', header, header, 1, 128)
    x = [int.from_bytes(b[4 * i:4 * i + 4], 'little') for i in range(32)]
    v = []
    for _ in range(n):
        v.append(x)
        x = block_mix(x)
    for _ in range(n):
        j = x[16] % n
        x = block_mix([x[i] ^ v[j][i] for i in range(32)])
    b = b''.join(w.to_bytes(4, 'little') for w in x)
    return hashlib.pbkdf2_hmac('sha256', header, b, 1, 32).hex()

def hashlib_scrypt(header):
    try:
        return hashlib.scrypt(header, salt=header, n=1024, r=1, p=1, dklen=32).hex()
    except (AttributeError, ValueError):
        return None

MASK = (1 << 64) - 1

def splitmix64(state):
    while True:
        state = (state + 0x9E3779B97F4A7C15) & MASK
        z = state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK
        yield z ^ (z >> 31)

# Must match fillTestData() in hashTestUtils.h and the constants in scryptTest.cpp
HEADER_SIZE = 80
COUNT = 128
DATA_SIZE = HEADER_SIZE * COUNT + 16
SEED = 0x5343525950540000
gen = splitmix64(SEED)
data = b''.join(next(gen).to_bytes(8, 'little') for _ in range(DATA_SIZE // 8))

print('// Generated by scryptVectors.py, do not edit')
print(f'// Digest of the header at Data[80 * i + i % 16], i = 0..{COUNT - 1}')
print('static const char *const ScryptVectors[] = {')
for i in range(COUNT):
    offset = HEADER_SIZE * i + i % 16
    header = data[offset:offset + HEADER_SIZE]
    digest = scrypt(header)
    reference = hashlib_scrypt(header)
    assert reference is None or reference == digest, i
    print(f'  "{digest}",')
print('};')
