# Generates ripemd160Vectors.h. hashlib has RIPEMD-160 only where OpenSSL still
# ships it, so the digests come from the textbook implementation below; it is
# checked against the vectors of the RIPEMD-160 paper, and against hashlib too
# when that has the algorithm.
#   python3 ripemd160Vectors.py > ripemd160Vectors.h
