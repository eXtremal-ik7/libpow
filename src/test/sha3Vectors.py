#!/usr/bin/env python3
# Generates sha3Vectors.h. hashlib carries SHA-3 but neither Keccak with its
# original padding nor the bare permutations, so those come from the textbook
# Keccak-p below - checked against hashlib and the published Keccak vectors
# before anything is printed.
#   python3 sha3Vectors.py > sha3Vectors.h
import hashlib

def rc_bit(t):
    if t % 255 == 0:
        return 1
    r = 1
    for _ in range(t % 255):
        r <<= 1
        if r & 0x100:
            r ^= 0x171
    return r & 1

def round_constant(ir, w):
    l = w.bit_length() - 1
    rc = 0
    for j in range(l + 1):
        rc |= rc_bit(j + 7 * ir) << ((1 << j) - 1)
    return rc

def rho_offsets(w):
    offsets = [[0] * 5 for _ in range(5)]
    x, y = 1, 0
    for t in range(24):
        offsets[x][y] = ((t + 1) * (t + 2) // 2) % w
        x, y = y, (2 * x + 3 * y) % 5
    return offsets

def keccak_p(lanes, w, rounds):
    mask = (1 << w) - 1
    rol = lambda v, n: ((v << n) | (v >> (w - n))) & mask if n else v
    offsets = rho_offsets(w)
    total = 12 + 2 * (w.bit_length() - 1)
    a = list(lanes)
    for ir in range(total - rounds, total):
        c = [a[x] ^ a[x + 5] ^ a[x + 10] ^ a[x + 15] ^ a[x + 20] for x in range(5)]
        d = [c[(x - 1) % 5] ^ rol(c[(x + 1) % 5], 1) for x in range(5)]
        a = [a[i] ^ d[i % 5] for i in range(25)]
        b = [0] * 25
        for x in range(5):
            for y in range(5):
                b[y + 5 * ((2 * x + 3 * y) % 5)] = rol(a[x + 5 * y], offsets[x][y])
        a = [b[i] ^ (~b[(i % 5 + 1) % 5 + 5 * (i // 5)] & b[(i % 5 + 2) % 5 + 5 * (i // 5)]) & mask for i in range(25)]
        a[0] ^= round_constant(ir, w)
    return a

def sponge(message, hash_size, padding):
    rate = 200 - 2 * hash_size
    padded = bytearray(message) + bytes([padding])
    padded += bytes(-len(padded) % rate)
    padded[-1] |= 0x80
    state = [0] * 25
    for offset in range(0, len(padded), rate):
        block = padded[offset:offset + rate]
        for i in range(rate // 8):
            state[i] ^= int.from_bytes(block[8 * i:8 * i + 8], 'little')
        state = keccak_p(state, 64, 24)
    out = b''.join(lane.to_bytes(8, 'little') for lane in state)
    return out[:hash_size].hex()

def keccak(message, hash_size):
    return sponge(message, hash_size, 0x01)

MASK = (1 << 64) - 1

def splitmix64(state):
    while True:
        state = (state + 0x9E3779B97F4A7C15) & MASK
        z = state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK
        yield z ^ (z >> 31)

# Must match fillTestData() in hashTestUtils.h and DataSeed in sha3Test.cpp
DATA_SIZE = 320
MAX_LENGTH = 300
SEED = 0x5348413300000000
gen = splitmix64(SEED)
data = b''.join(next(gen).to_bytes(8, 'little') for _ in range(DATA_SIZE // 8))

# The model has to agree with hashlib and with the published Keccak digests
for size in range(MAX_LENGTH):
    message = data[size % 16:size % 16 + size]
    for hash_size, ref in ((28, hashlib.sha3_224), (32, hashlib.sha3_256), (48, hashlib.sha3_384), (64, hashlib.sha3_512)):
        assert sponge(message, hash_size, 0x06) == ref(message).hexdigest()
assert keccak(b'', 32) == 'c5d2460186f7233c927e7db2dcc703c0e500b653ca82273b7bfad8045d85a470'
assert keccak(b'abc', 32) == '4e03657aea45a94fc7d47ba826c8d667c0d1e6e33a64a036ec44f58fa12d6c45'
assert keccak(b'', 64) == ('0eab42de4c3ceb9235fc91acffe746b29c29a8c366b7c60e4e67c466f36a4304'
                           'c00fa9caf9d87976ba469bcbe06713b435f091ef2769fb160cdab33d3670680e')

print('// Generated by sha3Vectors.py, do not edit')
print()
print(f'// Digests of Data[Size % 16 .. Size % 16 + Size), Size = 0..{MAX_LENGTH - 1}')
print('static const CLengthVector Sha3LengthVectors[] = {')
for size in range(MAX_LENGTH):
    message = data[size % 16:size % 16 + size]
    print('  {')
    print(f'    "{hashlib.sha3_256(message).hexdigest()}",')
    print(f'    "{hashlib.sha3_512(message).hexdigest()}",')
    print(f'    "{keccak(message, 32)}",')
    print(f'    "{keccak(message, 64)}"')
    print('  },')
print('};')
print()

def lanes_initializer(lanes, digits):
    rows = []
    for i in range(0, 25, 5):
        rows.append('  ' + ', '.join(f'0x{lane:0{digits}x}' for lane in lanes[i:i + 5]) + ',')
    return '\n'.join(rows)

print('// Keccak-f[1600] of the all zero state')
print('static const uint64_t Keccak1600OfZero[25] = {')
print(lanes_initializer(keccak_p([0] * 25, 64, 24), 16))
print('};')
print()

state800 = [int.from_bytes(data[4 * i:4 * i + 4], 'little') for i in range(25)]
print('// Keccak-p[800, 12 rounds] of the first 100 bytes of Data, read as little endian lanes')
print('static const uint32_t Keccak800Of12Rounds[25] = {')
print(lanes_initializer(keccak_p(state800, 32, 12), 8))
print('};')
