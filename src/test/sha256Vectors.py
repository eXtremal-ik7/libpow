#!/usr/bin/env python3
# Generates sha256Vectors.h: the reference digests come from hashlib, not from
# libpow, so the table is an outside opinion on the implementation.
#   python3 sha256Vectors.py > sha256Vectors.h
import hashlib

MASK = (1 << 64) - 1

def splitmix64(state):
    while True:
        state = (state + 0x9E3779B97F4A7C15) & MASK
        z = state
        z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK
        z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK
        yield z ^ (z >> 31)

# Must match fillTestData() in sha256Test.cpp
DATA_SIZE = 1280
SEED = 0x5348413235360000
gen = splitmix64(SEED)
data = b''.join(next(gen).to_bytes(8, 'little') for _ in range(DATA_SIZE // 8))

print('// Generated by sha256Vectors.py, do not edit')
print('// Digest of Data[Size % 16 .. Size % 16 + Size), Size = 0..1023')
print('static const char *const Sha256LengthVectors[] = {')
for size in range(1024):
    offset = size % 16
    print(f'  "{hashlib.sha256(data[offset:offset + size]).hexdigest()}",')
print('};')
